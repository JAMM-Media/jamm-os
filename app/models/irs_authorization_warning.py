# app/models/irs_authorization_warning.py

import uuid
from datetime import datetime, timezone
from typing import Optional

from sqlalchemy import DateTime, ForeignKey, Integer, UniqueConstraint
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.db.base_class import Base

RECIPIENT_COMMENT = (
    "User who received this tier in-app. NULL for rows written before "
    "Sep 24, 2026 or after the user was deleted."
)


class IrsAuthorizationWarning(Base):
    """
    Records an expiry warning that was actually sent for an IRS authorization.

    This table is the control gate for the warning ladder. It replaced the
    boolean expiry_notification_sent column on IrsAuthorization, which could
    only ever express "some warning went out at some point" and therefore
    could not support more than one tier.

    One row per recipient per tier, enforced by a database-level unique
    constraint on (authorization_id, threshold_days, recipient_user_id) rather
    than by an application check. Fired-once means any row exists for the tier,
    not one row: a tier that reached the owner and two managers leaves three
    rows and is still a tier that has fired. threshold_days is the tier,
    expressed as days before valid_until, where 0 means the expiry date itself.
    recipient_user_id is null on rows written before Sep 24, 2026, which are
    never backfilled, and on rows whose user was later deleted. The constraint
    uses Postgres' default NULLS DISTINCT so those nulls never collide.

    Rows for an authorization are still deleted when its valid_until changes,
    which resets the ladder for renewals and for corrected typos alike, so this
    table cannot answer who was warned before a date change. The permanent
    receipt is the irs_authorization.expiry_warning_sent behavioral event,
    which carries recipient_user_ids and emailed_user_ids and is append-only.

    A row is written only after the warning has actually been delivered, so
    the presence of a row is evidence of a send rather than an intent to
    send.
    """

    __tablename__ = "irs_authorization_warnings"

    __table_args__ = (
        UniqueConstraint(
            "authorization_id",
            "threshold_days",
            "recipient_user_id",
            name="uq_irs_auth_warning_auth_threshold_recipient",
        ),
    )

    id: Mapped[uuid.UUID] = mapped_column(
        primary_key=True,
        default=uuid.uuid4,
    )

    firm_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("firms.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )

    authorization_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("irs_authorizations.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )

    # The tier that fired, in days before valid_until. 0 is the expiry date.
    threshold_days: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
    )

    # SET NULL, not CASCADE: users are hard-deleted here, and a cascade would
    # take the compliance receipt with the person. The constraint name is
    # given explicitly so create_all and the migration build the same name,
    # rather than the test database carrying an autogenerated one.
    recipient_user_id: Mapped[Optional[uuid.UUID]] = mapped_column(
        ForeignKey(
            "users.id",
            ondelete="SET NULL",
            name="fk_irs_auth_warning_recipient_user",
        ),
        nullable=True,
        index=True,
        comment=RECIPIENT_COMMENT,
    )

    sent_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
    )

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        default=lambda: datetime.now(timezone.utc),
        nullable=False,
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        default=lambda: datetime.now(timezone.utc),
        onupdate=lambda: datetime.now(timezone.utc),
        nullable=False,
    )

    # --- Relationships ---
    firm: Mapped["Firm"] = relationship("Firm")
    authorization: Mapped["IrsAuthorization"] = relationship("IrsAuthorization")
    recipient: Mapped[Optional["User"]] = relationship("User")
